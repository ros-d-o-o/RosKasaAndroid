PROMPT === 1. PREGLED TESTNIH RACUNOV (RACGLAVA) ===
SELECT g.RACUN_ID,
       g.STATUS,
       g.MARKER,
       g.ZNESEK,
       g.PLACANO,
       g.FISKALIZACIJA,
       g.STKOPIJ,
       g.STORNO_RACUN_ID,
       g.KASIRAL,
       g.IZVOR_MOBILE_ID,
       TO_CHAR(g.DAN_URA, 'YYYY-MM-DD HH24:MI:SS') AS DAN_URA
FROM RACGLAVA g
WHERE (g.MARKER LIKE 'Miza 58%' OR g.MARKER LIKE 'Miza 59%' OR g.MARKER LIKE 'Miza 60%')
  AND g.DATUM >= TRUNC(SYSDATE)
ORDER BY g.RACUN_ID DESC;

PROMPT === 2. AVTOMATSKE KONTROLE (PASS / FAIL) ZA TESTNE RACUNE ===
WITH test_rac AS (
    SELECT g.RACUN_ID, g.STATUS, g.MARKER, NVL(g.ZNESEK, 0) AS ZNESEK,
           NVL(g.PLACANO, 0) AS PLACANO, g.FISKALIZACIJA, g.STORNO_RACUN_ID,
           (SELECT NVL(SUM(NVL(p.ZNESEK, 0) - NVL(p.ZNESEK_POPUST, 0)), 0) FROM RACPOZIC p WHERE p.RACUN_ID = g.RACUN_ID) AS SUM_POZIC,
           (SELECT COUNT(*) FROM RACPOZIC p WHERE p.RACUN_ID = g.RACUN_ID) AS CNT_POZIC,
           (SELECT NVL(SUM(NVL(pl.DELNI_ZNESEK, NVL(pl.ZNESEK, 0))), 0) FROM RACPLACI pl WHERE pl.RACUN_ID = g.RACUN_ID) AS SUM_PLACI,
           (SELECT COUNT(*) FROM RACPLACI pl
              JOIN NACPLAC np ON np.PLACILO_ID = pl.PLACILO_ID
             WHERE pl.RACUN_ID = g.RACUN_ID AND pl.PLACILO_ID <> 99 AND np.FISKALNO = 1) AS CNT_FISK_PLAC,
           (SELECT COUNT(*) FROM RACIZPISAN ri WHERE ri.RACUN_ID = g.RACUN_ID AND DBMS_LOB.GETLENGTH(ri.VSEBINA) > 0) AS CNT_IZPIS,
           (SELECT COUNT(*) FROM RACPLACI pl WHERE pl.RACUN_ID = g.RACUN_ID AND pl.PLACILO_ID = 12
              AND pl.PARTNER_ID IS NULL AND pl.NAZIV_PARTNER IS NULL) AS DOB_BREZ_PARTNERJA,
           (SELECT COUNT(*) FROM RACPLACI pl WHERE pl.RACUN_ID = g.RACUN_ID AND pl.PLACILO_ID = 31
              AND pl.GOST_PRIJAVA_ID IS NULL AND pl.A_GOSTNAZIV IS NULL) AS HOTEL_BREZ_GOSTA
    FROM RACGLAVA g
    WHERE (g.MARKER LIKE 'Miza 58%' OR g.MARKER LIKE 'Miza 59%' OR g.MARKER LIKE 'Miza 60%')
      AND g.DATUM >= TRUNC(SYSDATE)
)
SELECT RACUN_ID,
       MARKER,
       STATUS,
       ZNESEK,
       CASE WHEN ABS(ZNESEK - SUM_POZIC) <= 0.02 THEN 'PASS' ELSE 'FAIL (POZ=' || SUM_POZIC || ')' END AS CHK_POZICIJE,
       CASE WHEN STATUS <> 2 THEN 'N/A'
            WHEN ABS(ZNESEK - PLACANO) <= 0.02 AND ABS(ZNESEK - SUM_PLACI) <= 0.02 THEN 'PASS'
            ELSE 'FAIL (PL=' || SUM_PLACI || ')' END AS CHK_PLACILA,
       CASE WHEN STATUS <> 2 THEN 'N/A'
            WHEN CNT_FISK_PLAC > 0 AND NVL(FISKALIZACIJA, 0) = 1 THEN 'PASS'
            WHEN CNT_FISK_PLAC = 0 AND NVL(FISKALIZACIJA, 0) <> 1 THEN 'PASS'
            ELSE 'FAIL (FISK=' || NVL(TO_CHAR(FISKALIZACIJA),'NULL') || ')' END AS CHK_FISKAL,
       CASE WHEN STATUS <> 2 THEN 'N/A'
            WHEN CNT_IZPIS > 0 THEN 'PASS'
            ELSE 'FAIL (NI IZPISA)' END AS CHK_IZPIS,
       CASE WHEN DOB_BREZ_PARTNERJA = 0 AND HOTEL_BREZ_GOSTA = 0 THEN 'PASS'
            ELSE 'FAIL (PARTNER/GOST)' END AS CHK_VEZAVE
FROM test_rac
ORDER BY RACUN_ID DESC;

PROMPT === 3. PODROBNOSTI POZICIJ (RACPOZIC) ===
SELECT p.RACUN_ID, p.POZICIJA_ID, p.NIVO4_ID, SUBSTR(n.NAZIV, 1, 30) AS ARTIKEL,
       p.KOLICINA, p.CENA, p.ZNESEK, p.STOPNJA_DAVKA, p.PAKET_KOL, p.STORNIRANA
FROM RACPOZIC p
JOIN RACGLAVA g ON g.RACUN_ID = p.RACUN_ID
LEFT JOIN NIVO4 n ON n.NIVO4_ID = p.NIVO4_ID
WHERE (g.MARKER LIKE 'Miza 58%' OR g.MARKER LIKE 'Miza 59%' OR g.MARKER LIKE 'Miza 60%')
  AND g.DATUM >= TRUNC(SYSDATE)
ORDER BY p.RACUN_ID DESC, p.POZICIJA_ID;

PROMPT === 4. PODROBNOSTI PLACIL (RACPLACI) ===
SELECT pl.RACUN_ID, pl.POZICIJA_ID, pl.PLACILO_ID, np.NAZIV AS NACIN_PLACILA,
       pl.DELNI_ZNESEK, pl.ZNESEK, pl.PARTNER_ID, SUBSTR(pl.NAZIV_PARTNER, 1, 25) AS PARTNER,
       pl.GOST_PRIJAVA_ID, SUBSTR(pl.A_GOSTNAZIV, 1, 25) AS GOST
FROM RACPLACI pl
JOIN RACGLAVA g ON g.RACUN_ID = pl.RACUN_ID
LEFT JOIN NACPLAC np ON np.PLACILO_ID = pl.PLACILO_ID
WHERE (g.MARKER LIKE 'Miza 58%' OR g.MARKER LIKE 'Miza 59%' OR g.MARKER LIKE 'Miza 60%')
  AND g.DATUM >= TRUNC(SYSDATE)
ORDER BY pl.RACUN_ID DESC, pl.POZICIJA_ID;

PROMPT === 5. ZADNJI ZAPISI V KRONOLOGIJI (OSEBA_ID = 9999, DANES, TOP 20) ===
SELECT * FROM (
    SELECT KRONOLOG_AI, TO_CHAR(DATUM_URA, 'HH24:MI:SS') AS URA,
           OSEBA_ID, SUBSTR(OPIS_OPERACIJE, 1, 100) AS OPIS
    FROM KRONOLOGIJA
    WHERE OSEBA_ID = 9999
      AND DATUM_URA >= TRUNC(SYSDATE)
    ORDER BY KRONOLOG_AI DESC
) WHERE ROWNUM <= 20;

