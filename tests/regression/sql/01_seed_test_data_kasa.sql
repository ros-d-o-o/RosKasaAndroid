-- Preverjanje predpogojev za regresijske teste RosKasa / Light16 / Mobile2027
-- Kodna tabela: EE8MSWIN1250 (brez UTF-8 BOM)
-- Baza: GASTS/GASTS@ROS | MOBILE_ID = 6 | PIN = 9999
-- ============================================================================
SET PAGESIZE 200 LINESIZE 300 FEEDBACK OFF TRIMSPOOL ON VERIFY OFF

PROMPT ========================================================================
PROMPT [01] PREVERJANJE PREDPOGOJEV ZA REGRESIJSKE TESTE (MOBILE_ID=6, PIN=9999)
PROMPT ========================================================================

PROMPT === 1. MOBILE_SETUP (MOBILE_SETUP_ID = 6) ===
SELECT MOBILE_SETUP_ID, NAZIV, TOCILNICA_ID, KUHINJA_ID, F_POS_ID, FISKALIZACIJA, POPUST99, HIS_OBRAT
FROM MOBILE_SETUP
WHERE MOBILE_SETUP_ID = 6;

PROMPT === 2. NATAKAR / OSEBJE (PIN / OSEBA_ID = 9999) ===
SELECT OSEBA_ID, PRIIMEK, IME
FROM OSEBJE
WHERE OSEBA_ID = 9999;

PROMPT === 3. PLACILA (1=GOTOVINA, 5=KRED.K.ROCNO, 12=DOBAVNICA, 31=GOST HOTELA, 99=POPUST) ===
SELECT PLACILO_ID, NAZIV, METODA, VRSTA, FISKALNO
FROM NACPLAC
WHERE PLACILO_ID IN (1, 5, 12, 31, 99)
ORDER BY PLACILO_ID;

PROMPT === 4. TESTNI ARTIKLI (NIVO4) ===
SELECT NIVO4_ID, NAZIV
FROM NIVO4
WHERE NIVO4_ID IN (809010081, 318130001, 315070022, 315070008)
ORDER BY NIVO4_ID;

PROMPT === 5. SESTAVA PAKETA (809010081 - PAKET KREMNA REZINA) ===
SELECT DISTINCT v.CENIKVRNIVO4_ID AS PAKET_ID, v.NIVO4_ID AS PODARTIKEL_ID, n.NAZIV, v.KOLICINA
FROM CENIKVR_VR v
LEFT JOIN NIVO4 n ON n.NIVO4_ID = v.NIVO4_ID
WHERE v.CENIKVRNIVO4_ID = 809010081
ORDER BY v.NIVO4_ID;

PROMPT === 6. TESTNI PARTNERJI ZA DOBAVNICO (41125 ROS D.O.O., 654330 PRVA OSEBNA ZAVAROVALNICA) ===
SELECT PARTNER_ID, NAZIV
FROM PARTNER
WHERE PARTNER_ID IN (41125, 654330)
ORDER BY PARTNER_ID;

PROMPT === 7. TRENUTNO ODPRTI RACUNI NA TESTNIH MIZAH (Miza 58, 59, 60) ===
SELECT RACUN_ID, STATUS, MARKER, ZNESEK, PLACANO, KASIRAL, IZVOR_MOBILE_ID,
       TO_CHAR(DATUM, 'YYYY-MM-DD') AS DATUM
FROM RACGLAVA
WHERE MARKER IN ('Miza 58', 'Miza 59', 'Miza 60')
  AND STATUS = 1
ORDER BY RACUN_ID DESC;

PROMPT [01] KONEC PREVERJANJA PREDPOGOJEV.
EXIT;